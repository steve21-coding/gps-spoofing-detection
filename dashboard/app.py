"""Overview page. Run with:  streamlit run dashboard/app.py"""
import pandas as pd
import streamlit as st

from common import page_setup, require_metrics  # noqa: I001
from ml.src.predict import list_models

page_setup("GPS Spoofing Detection")
m = require_metrics()
sel = m["selected"]
sel_res = m["models"][sel["feature_set"]][sel["model"]]

st.markdown(
    "Detect **suspicious GPS behaviour** in navigation data using three complementary approaches, always reported "
    "separately: **supervised classifiers**, an **unsupervised anomaly detector**, and **rule-based physical-plausibility "
    "checks** (which are *not* machine learning).")

st.subheader("Detection workflow")
st.markdown("`Navigation CSV` → **Validation** → **Causal feature engineering** → **Model scoring + rule checks** → "
            "**Threshold & persistence** → **Result: normal / suspicious / potential spoofing, with reasons**")
c1, c2, c3 = st.columns(3)
c1.markdown("**normal**  \nNo model alert and no rule fired.")
c2.markdown("**suspicious**  \nA rule fired and/or the unsupervised detector flagged it. Ordinary GPS errors look like this too.")
c3.markdown("**potential spoofing**  \nA supervised model trained on labelled (simulated) attacks flagged it. Still not proof.")

st.subheader("Dataset")
sp = m["split"]
d1, d2, d3, d4 = st.columns(4)
d1.metric("Simulated flights", m["meta"]["n_trajectories"])
d2.metric("Train / val / test flights", f"{sp['train']['trajectories']} / {sp['val']['trajectories']} / {sp['test']['trajectories']}")
d3.metric("Rows (1 Hz)", f"{sum(v['rows'] for v in sp.values()):,}")
d4.metric("Seed", m["meta"]["seed"])
st.caption("Data are generated by `ml/src/synthetic_data.py` (no real GNSS measurements). Splits are by whole flight so "
           "correlated samples from one flight never appear in both training and testing. Benign problems (glitches, "
           "dropouts, poor visibility) are labelled *not spoofing* on purpose.")
sc = pd.DataFrame(m["trajectories_by_scenario"]).fillna(0).astype(int)
st.dataframe(sc.rename_axis("scenario"), width="stretch")

st.subheader("Selected model")
t = sel_res["test"]
st.markdown(f"`{sel['feature_set']}` feature set · **{sel['model'].replace('_', ' ')}** · chosen by {sel['selected_by']} · "
            f"threshold {sel_res['threshold']:.3f} ({sel_res['threshold_source']})")
k = st.columns(5)
for col, (label, v) in zip(k, [("Precision", t["precision"]), ("Recall", t["recall"]), ("F1", t["f1"]),
                               ("False-positive rate", t["false_positive_rate"]), ("PR-AUC", t["pr_auc"])]):
    col.metric(label, f"{v:.3f}")
st.caption("Held-out **test** split, row level, simulated data, no alert persistence. See *Model Comparison* for all models, "
           "per-attack results and generalisation.")

st.subheader("Available trained models")
st.dataframe(pd.DataFrame(list_models()).rename(columns={"key": "artifact"}), width="stretch", hide_index=True)

st.subheader("Important limitations")
st.markdown("""
- **Simulated data only.** The models learned simulated attack patterns. Independent real-world GNSS data has not been tested.
- **Persistent offsets are hard.** Without reported speed or signal features, a smooth position offset is hard to tell from real motion.
- **Single-sample alerts are noisy.** At the default operating point most clean flights raise at least one alert; requiring several consecutive alerts (see *Spoofing Analysis*) trades delay for fewer false alarms.
- **Probabilities are not calibrated.** Treat scores as rankings, not literal probabilities.
- **Not a safety-critical system.** Do not use for navigation or operational decisions.
""")
